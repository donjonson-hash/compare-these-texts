import {createServer} from 'node:http';
import {readFile, writeFile, mkdir, stat} from 'node:fs/promises';
import {dirname, resolve, extname, sep} from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const root=resolve(process.env.OCR_PILOT_ROOT || dirname(fileURLToPath(import.meta.url)));
const types={'.html':'text/html','.mjs':'text/javascript','.js':'text/javascript','.wasm':'application/wasm','.json':'application/json','.png':'image/png','.gz':'application/gzip','.pdf':'application/pdf'};
const server=createServer(async(req,res)=>{try{const p=resolve(root,'.'+decodeURIComponent(new URL(req.url,'http://localhost').pathname));if(p!==root&&!p.startsWith(root+sep))throw Error('Path');const f=(await stat(p)).isDirectory()?resolve(p,'index.html'):p;res.setHeader('Content-Type',types[extname(f)]||'application/octet-stream');res.end(await readFile(f));}catch{res.statusCode=404;res.end('Not found');}});
await new Promise(r=>server.listen(0,'127.0.0.1',r));
const origin=`http://127.0.0.1:${server.address().port}`;
let browser;
const report={created_at:new Date().toISOString(),checks:[],outbound:[],page_errors:[]};
try {
 browser=await chromium.launch({headless:true,args:['--no-sandbox'],...(process.env.CHROMIUM_EXECUTABLE?{executablePath:process.env.CHROMIUM_EXECUTABLE}:{})});
 report.browser=browser.version();
 const context=await browser.newContext({acceptDownloads:true,viewport:{width:1440,height:1100}});
 await context.route('**/*',route=>{const url=route.request().url();if(!url.startsWith(origin+'/')){report.outbound.push(url);return route.abort();}return route.continue();});
 const page=await context.newPage();page.on('pageerror',e=>report.page_errors.push(e.message));
 await page.goto(origin);await page.waitForSelector('section');
 const panel=i=>page.locator('section').nth(i);
 const status=i=>panel(i).locator('.status');
 const waitReady=async i=>page.waitForFunction(i=>!document.querySelectorAll('section')[i].querySelector('.recognize').disabled,i,{timeout:120000});
 const upload=async(i,name)=>{await panel(i).locator('input[type=file]').setInputFiles(resolve(root,'fixtures/pdf',name));await waitReady(i);};
 const select=async(i,n)=>{await panel(i).locator('.page-select').selectOption({value:String(n-1)});await waitReady(i);};
 const recognize=async i=>{await panel(i).locator('.recognize').click();await page.waitForFunction(i=>{const p=document.querySelectorAll('section')[i];return !p.querySelector('.recognize').disabled&&!p.querySelector('.confirm').disabled;},i,{timeout:120000});};
 const confirm=async i=>panel(i).locator('.confirm').click();
 let firstText,scanText;
 for(const i of [0,1]){
   await upload(i,'mixed.pdf');
   assert.equal(await panel(i).locator('.page-select option').count(),2);
   const text=await panel(i).locator('textarea').inputValue();assert.ok(text.trim().length>30,'text layer must extract without OCR');
   assert.match(await status(i).textContent(),/Text layer extracted/);
   if(i===0)firstText=text;else assert.equal(text,firstText);
   await confirm(i);assert.equal(await panel(i).locator('.download').isDisabled(),true,'unreviewed PDF page blocks download');
   await select(i,2);assert.equal(await panel(i).locator('textarea').inputValue(),'');
   assert.match(await status(i).textContent(),/No usable text layer/);
   await recognize(i);const recognized=await panel(i).locator('textarea').inputValue();assert.ok(recognized.trim().length>30,'real OCR produces scan text');
   if(i===0)scanText=recognized;else assert.equal(recognized,scanText);
   await confirm(i);assert.equal(await panel(i).locator('.download').isDisabled(),false);
   await select(i,1);assert.equal(await panel(i).locator('textarea').inputValue(),firstText);
   assert.match(await status(i).textContent(),/already checked/);
   assert.match(await panel(i).locator('.review-count').textContent(),/2 of 2 pages confirmed/);
 }
 report.checks.push('mixed PDF text-layer routing, scanned-page OCR, all-page confirmation, navigation preserves reviewed text');
 await page.locator('#compare').click();assert.equal(await page.locator('#summary').textContent(),'Confirmed texts are identical.');
 const [download]=await Promise.all([page.waitForEvent('download'),panel(0).locator('.download').click()]);
 assert.equal(await download.failure(),null);const content=await readFile(await download.path(),'utf8');
 assert.equal(content,`[Page 1]\n${firstText}\n\n[Page 2]\n${scanText}`);
 report.checks.push('complete reviewed PDF exports TXT with page boundaries');
 await panel(0).locator('textarea').fill(firstText+'\nManual change');
 assert.equal(await page.locator('#compare').isDisabled(),true);assert.equal(await panel(0).locator('.download').isDisabled(),true);
 assert.match(await panel(0).locator('.review-count').textContent(),/1 of 2 pages confirmed/);
 await select(0,2);assert.equal(await panel(0).locator('textarea').inputValue(),scanText);assert.match(await status(0).textContent(),/already checked/);
 await select(0,1);assert.equal(await panel(0).locator('textarea').inputValue(),firstText+'\nManual change');await confirm(0);
 await page.locator('#compare').click();assert.match(await page.locator('#summary').textContent(),/differing line positions/);
 assert.equal(await page.locator('#result h3').first().textContent(),'Page 1');
 await page.locator('#result button').first().click();await waitReady(0);
 report.checks.push('editing invalidates only edited page, blocks whole-document comparison/export, page-level difference navigation');
 await mkdir(resolve(root,'results'),{recursive:true});await page.screenshot({path:resolve(root,'results/pdf-pilot.png'),fullPage:true});
 await upload(0,'blank.pdf');assert.equal(await panel(0).locator('textarea').inputValue(),'');assert.equal(await panel(0).locator('.confirm').isDisabled(),true);
 await panel(0).locator('.blank').check();await confirm(0);assert.equal(await panel(0).locator('.download').isDisabled(),false);
 await panel(0).locator('textarea').fill('Now text');assert.equal(await panel(0).locator('.blank').isChecked(),false);assert.equal(await panel(0).locator('.download').isDisabled(),true);
 report.checks.push('blank page requires explicit no-text confirmation; editing clears blank approval');
 for(const name of ['too-many-pages.pdf','corrupt.pdf']){
   await panel(0).locator('input[type=file]').setInputFiles(resolve(root,'fixtures/pdf',name));
   await page.waitForFunction(()=>document.querySelector('section .status').textContent.startsWith('Cannot open document:'),null,{timeout:30000});
   assert.equal(await panel(0).locator('.recognize').isDisabled(),true);assert.equal(await panel(0).locator('.download').isDisabled(),true);
   assert.equal(await panel(0).locator('.full-size').getAttribute('href'),null);
 }
 report.checks.push('page-count limit and corrupt PDF reject without stale text/export');
 await upload(0,'scan-a.pdf');await panel(0).locator('.recognize').click();await panel(0).locator('.cancel').click();
 await upload(0,'mixed.pdf');await page.waitForTimeout(1500);assert.equal(await panel(0).locator('textarea').inputValue(),firstText);
 assert.equal(await panel(0).locator('.download').isDisabled(),true);
 report.checks.push('cancel OCR then replace PDF: no late OCR overwrites new text layer');
 assert.deepEqual(report.outbound,[]);assert.deepEqual(report.page_errors,[]);
 report.status='passed';
 await writeFile(resolve(root,'results/pdf-browser-smoke.json'),JSON.stringify(report,null,2)+'\n');
 console.log(JSON.stringify(report,null,2));
} catch(error) {
 report.status='failed';report.error=error.stack;
 await mkdir(resolve(root,'results'),{recursive:true});await writeFile(resolve(root,'results/pdf-browser-smoke.json'),JSON.stringify(report,null,2)+'\n');
 throw error;
} finally {if(browser)await browser.close();await new Promise(r=>server.close(r));}
