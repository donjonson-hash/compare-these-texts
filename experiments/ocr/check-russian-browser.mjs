import {createServer} from 'node:http';
import {readFile, writeFile, mkdir, stat} from 'node:fs/promises';
import {dirname, resolve, extname, sep} from 'node:path';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
import {chromium} from 'playwright';

const runnerRoot=dirname(fileURLToPath(import.meta.url));
const root=resolve(process.env.OCR_PILOT_ROOT || runnerRoot);
const types={'.html':'text/html','.mjs':'text/javascript','.js':'text/javascript','.wasm':'application/wasm','.json':'application/json','.png':'image/png','.gz':'application/gzip','.pdf':'application/pdf'};
const server=createServer(async(req,res)=>{try{const p=resolve(root,'.'+decodeURIComponent(new URL(req.url,'http://localhost').pathname));if(p!==root&&!p.startsWith(root+sep))throw Error('Path');const f=(await stat(p)).isDirectory()?resolve(p,'index.html'):p;res.setHeader('Content-Type',types[extname(f)]||'application/octet-stream');res.end(await readFile(f));}catch{res.statusCode=404;res.end('Not found');}});
await new Promise(r=>server.listen(0,'127.0.0.1',r));
const origin='http://127.0.0.1:'+server.address().port;
const report={created_at:new Date().toISOString(),fixture:'rus-paragraphs-a',checks:[],outbound:[],page_errors:[]};
const evaluate=(reference,hypothesis)=>JSON.parse(execFileSync('python3',['-c','import sys,json; sys.path.insert(0,sys.argv[1]); from metrics import evaluate; d=json.load(sys.stdin); print(json.dumps(evaluate(d["reference"],d["hypothesis"])))',runnerRoot],{input:JSON.stringify({reference,hypothesis}),encoding:'utf8'}));
const scripts=text=>{const cyrillic=(text.match(/\p{Script=Cyrillic}/gu)||[]).length,latin=(text.match(/\p{Script=Latin}/gu)||[]).length;return {cyrillic,latin,cyrillic_share:cyrillic/Math.max(1,cyrillic+latin)};};
let browser;
try{
 browser=await chromium.launch({headless:true,args:['--no-sandbox'],...(process.env.CHROMIUM_EXECUTABLE?{executablePath:process.env.CHROMIUM_EXECUTABLE}:{})});
 report.browser=browser.version();
 const context=await browser.newContext({acceptDownloads:true,locale:'en-US',viewport:{width:1440,height:1100}});
 await context.route('**/*',route=>{const url=route.request().url();if(!url.startsWith(origin+'/')){report.outbound.push(url);return route.abort();}return route.continue();});
 const page=await context.newPage();page.on('pageerror',e=>report.page_errors.push(e.message));
 await page.goto(origin);await page.waitForSelector('section');
 const panel=i=>page.locator('section').nth(i);
 const language=async(i,value)=>panel(i).locator('.language').selectOption({value});
 const ready=async i=>page.waitForFunction(i=>!document.querySelectorAll('section')[i].querySelector('.recognize').disabled,i,{timeout:120000});
 const upload=async(i,name)=>{await panel(i).locator('input[type=file]').setInputFiles(resolve(root,'fixtures',name));await ready(i);};
 const selectPage=async(i,number)=>{await panel(i).locator('.page-select').selectOption({value:String(number-1)});await ready(i);};
 const recognize=async i=>{await panel(i).locator('.recognize').click();await page.waitForFunction(i=>{const p=document.querySelectorAll('section')[i];return !p.querySelector('.recognize').disabled&&!p.querySelector('.confirm').disabled;},i,{timeout:120000});return panel(i).locator('textarea').inputValue();};
 await language(0,'rus');
 await upload(0,'rus-paragraphs-a.png');
 assert.equal(await panel(0).locator('.language').inputValue(),'rus','language selected before upload must not reset to English');
 const russian=await recognize(0);
 assert.match(russian,/Заказчик/);
 assert.match(russian,/Срок доставки/);
 assert.ok(scripts(russian).cyrillic_share>.9,'Russian model should return predominantly Cyrillic on this fixture');
 report.checks.push('Russian selected before upload survives initialization and real OCR returns Cyrillic');
 await language(1,'eng');await upload(1,'rus-paragraphs-a.png');
 const english=await recognize(1);
 assert.ok(scripts(english).cyrillic_share<.2,'English control reproduces predominantly Latin misrecognition');
 const reference=await readFile(resolve(root,'fixtures/rus-paragraphs-a.txt'),'utf8');
 report.fixture_sha256=createHash('sha256').update(await readFile(resolve(root,'fixtures/rus-paragraphs-a.png'))).digest('hex');
 report.reference_sha256=createHash('sha256').update(reference).digest('hex');
 report.recognition={english_model:{text:english,scripts:scripts(english),metrics:evaluate(reference,english)},russian_model:{text:russian,scripts:scripts(russian),metrics:evaluate(reference,russian)}};
 assert.ok(report.recognition.russian_model.metrics.cer<report.recognition.english_model.metrics.cer,'correct model must improve exact character fidelity on same bytes');
 report.checks.push('same-image English control reproduces script mismatch; Russian model has lower measured CER');
 assert.equal(await panel(0).locator('textarea').evaluate(el=>el.translate),false,'document text opts out of browser translation');
 await panel(0).locator('.confirm').click();
 const [download]=await Promise.all([page.waitForEvent('download'),panel(0).locator('.download').click()]);
 assert.equal(await download.failure(),null);
 assert.equal(await readFile(await download.path(),'utf8'),russian);
 report.checks.push('reviewed Cyrillic TXT download preserves exact OCR bytes; document text opts out of translation');
 await language(0,'eng');
 assert.equal(await panel(0).locator('.download').isDisabled(),true);
 await language(0,'rus');
 await upload(0,'rus-paragraphs-b.png');
 assert.equal(await panel(0).locator('.language').inputValue(),'rus','replacement must keep language preference');
 report.checks.push('language change invalidates approval; replacement retains chosen language');
 await upload(0,'pdf/scan-a.pdf');
 assert.equal(await panel(0).locator('.language').inputValue(),'rus');
 await language(0,'eng');
 await selectPage(0,2);
 assert.equal(await panel(0).locator('.language').inputValue(),'eng','unvisited page inherits updated preference');
 await language(0,'rus');
 await selectPage(0,1);
 assert.equal(await panel(0).locator('.language').inputValue(),'eng','previously visited page retains its own recognition settings');
 await selectPage(0,3);
 assert.equal(await panel(0).locator('.language').inputValue(),'rus','remaining unvisited page inherits latest preference');
 await upload(0,'rus-paragraphs-a.png');
 assert.equal(await panel(0).locator('.language').inputValue(),'rus');
 report.checks.push('unvisited PDF pages inherit language changes while visited page settings remain intact');
 await recognize(0);
 await mkdir(resolve(root,'results'),{recursive:true});
 await page.screenshot({path:resolve(root,'results/russian-language-pilot.png'),fullPage:true});
 assert.deepEqual(report.outbound,[]);assert.deepEqual(report.page_errors,[]);
 report.status='passed';
 await writeFile(resolve(root,'results/russian-browser-smoke.json'),JSON.stringify(report,null,2)+'\n');
 console.log(JSON.stringify({status:report.status,checks:report.checks,english_cer:report.recognition.english_model.metrics.cer,russian_cer:report.recognition.russian_model.metrics.cer,outbound:report.outbound,page_errors:report.page_errors},null,2));
}catch(error){
 report.status='failed';report.error=error.stack;
 await mkdir(resolve(root,'results'),{recursive:true});await writeFile(resolve(root,'results/russian-browser-smoke.json'),JSON.stringify(report,null,2)+'\n');
 throw error;
}finally{if(browser)await browser.close();await new Promise(r=>server.close(r));}
